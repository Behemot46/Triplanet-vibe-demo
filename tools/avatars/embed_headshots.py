#!/usr/bin/env python3
"""Crop the chosen AI headshots and write v6/s0_avatars.js (AVATARS, AVATAR_KIND='photo').

Input: PICKS below -> SRC_DIR/<Name>_<seed>.png from gen_headshots.py (512 px).
Output: tools/avatars/out/<Name>.webp (160 px, committed) and v6/s0_avatars.js.
With no SRC_DIR, it rebuilds s0_avatars.js from the committed out/*.webp.
Usage: python3 embed_headshots.py [SRC_DIR]
"""
import base64, os, sys
from PIL import Image
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(HERE, 'out')
PICKS = {'Ella': 11, 'Priya': 23, 'Dana': 11, 'Marcus': 23, 'Grace': 23, 'Luis': 11, 'Tom': 11, 'Maya': 11,
         # v8.4 viewpoints (14 Nov 2026): ops coordinator, group leader, traveler, supplier contact, tour director
         'Kelsey': 11, 'Alan': 11, 'Linda': 11, 'Morgan': 11, 'Wade': 11}
CROP = (48, 0, 464, 416)   # head and shoulders, square
os.makedirs(OUT, exist_ok=True)
if len(sys.argv) > 1:
    for n, s in PICKS.items():
        if not os.path.exists(os.path.join(sys.argv[1], f'{n}_{s}.png')):
            continue   # keep the committed crop for people not in this run
        im = Image.open(os.path.join(sys.argv[1], f'{n}_{s}.png')).convert('RGB').crop(CROP).resize((160, 160), Image.LANCZOS)
        im.save(os.path.join(OUT, f'{n}.webp'), 'WEBP', quality=80, method=6)
av = {}
for n in PICKS:
    b = open(os.path.join(OUT, f'{n}.webp'), 'rb').read()
    av[n] = 'data:image/webp;base64,' + base64.b64encode(b).decode()
import json
with open(os.path.join(ROOT, 'v6', 's0_avatars.js'), 'w') as f:
    f.write('/* GENERATED by tools/avatars/embed_headshots.py. AI-generated headshots of FICTIONAL people who do not exist '
            '(Realistic Vision 5.1 + LCM-LoRA on Stable Diffusion 1.5; see tools/avatars/gen_headshots.py). */\n')
    f.write("const AVATAR_KIND='photo';\nconst AVATARS=" + json.dumps(av) + ';\n')
print('avatars', len(av), 'bytes', sum(len(v) for v in av.values()))
