#!/usr/bin/env python3
"""Embed the sourced Wikimedia Commons photos into the demo.

Reads tools/photos/manifest.json (written by the photo-sourcing pass) and the WebP files it
lists, and writes v6/s0_photos.js with:
  PHOTOS  = {dest:{key:dataURI}, venue:{id:dataURI}, hotel:{id:dataURI}}
  PHOTO_CREDITS = [{kind, id, title, author, license, license_url, source_url}]
Only Public domain, CC0, CC BY and CC BY-SA files are accepted; anything else is skipped.
Run from the repo root:  python3 tools/photos/build_photos.py
"""
import base64, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PH = os.path.join(ROOT, 'tools', 'photos')
OK = re.compile(r'^(public domain|pd|cc0|cc[- ]by( |-|$)|cc[- ]by[- ]sa)', re.I)

man = json.load(open(os.path.join(PH, 'manifest.json'), encoding='utf-8'))
photos, credits, skipped, size = {'dest': {}, 'venue': {}, 'hotel': {}}, [], [], 0
for kind in ('dest', 'venue', 'hotel'):
    for key, m in sorted((man.get(kind) or {}).items()):
        lic = (m.get('license') or '').strip()
        if not OK.match(lic) or re.search(r'\bNC\b|\bND\b|noncommercial|noderiv', lic, re.I):
            skipped.append((kind, key, lic)); continue
        f = os.path.join(PH, m['file']) if not os.path.isabs(m['file']) else m['file']
        if not os.path.exists(f):
            f = os.path.join(ROOT, m['file'])
        if not os.path.exists(f):
            skipped.append((kind, key, 'missing file')); continue
        b = open(f, 'rb').read(); size += len(b)
        photos[kind][key] = 'data:image/webp;base64,' + base64.b64encode(b).decode()
        author = re.sub(r'<[^>]+>', '', m.get('author') or '').strip() or 'Unknown author'
        credits.append({'kind': kind, 'id': key, 'title': m.get('title', ''), 'author': author[:120],
                        'license': lic, 'license_url': m.get('license_url', ''), 'source_url': m.get('source_url', '')})

out = os.path.join(ROOT, 'v6', 's0_photos.js')
with open(out, 'w', encoding='utf-8') as fh:
    fh.write('/* GENERATED by tools/photos/build_photos.py from Wikimedia Commons (see PHOTO_CREDITS). Do not edit. */\n')
    fh.write('const PHOTOS=' + json.dumps(photos, separators=(',', ':')) + ';\n')
    fh.write('const PHOTO_CREDITS=' + json.dumps(credits, ensure_ascii=False, separators=(',', ':')) + ';\n')
print('photos', {k: len(v) for k, v in photos.items()}, 'bytes', size, 'skipped', skipped)
