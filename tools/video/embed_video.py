#!/usr/bin/env python3
"""Embed the 720p booth loop (rendered with HyperFrames from tools/video/booth-loop) into the demo.
Writes v6/s0_video.js with BOOTH_VIDEO as a data URI. Run from the repo root after rendering:
  cd tools/video/booth-loop && npx hyperframes render -o ../out/triplanet-booth-loop.mp4 -q delivery
  ffmpeg -i ../out/triplanet-booth-loop.mp4 -vf scale=1280:-2 -c:v libx264 -crf 27 -preset slow -movflags +faststart -an ../out/booth-loop-720.mp4
  python3 tools/video/embed_video.py"""
import base64, os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
b = open(os.path.join(ROOT, 'tools', 'video', 'out', 'booth-loop-720.mp4'), 'rb').read()
with open(os.path.join(ROOT, 'v6', 's0_video.js'), 'w') as f:
    f.write('/* GENERATED by tools/video/embed_video.py: the 31 s booth loop, made with HyperFrames (tools/video/booth-loop). */\n')
    f.write("const BOOTH_VIDEO='data:video/mp4;base64," + base64.b64encode(b).decode() + "';\n")
print('embedded', len(b), 'bytes')
